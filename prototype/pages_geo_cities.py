def _time_line(name_prep, shift):
    if shift == 0:
        return f"В {name_prep} расписание совпадает с московским: удобно выбирать время без пересчёта."
    sign = "+" if shift > 0 else "−"
    return (f"В {name_prep} разница с московским временем {sign}{abs(shift)} ч. "
            "Расписание групп при записи подбираем с учётом вашего часового пояса.")


