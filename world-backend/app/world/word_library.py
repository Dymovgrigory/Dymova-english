def _photo_file(slug: str) -> str:
    if not slug:
        return ""
    root = Path(__file__).resolve().parents[3] / "world" / "public" / "learn" / "words"
    for ext in (".jpg", ".webp", ".png"):
        path = root / f"{slug}{ext}"
        if path.exists() and path.stat().st_size > 8000:
            return f"/learn/words/{slug}{ext}"
    return ""


def shows_picture(en: str) -> bool:
    return bool(image_path(en))


def image_path(en: str) -> str:
    slug = "".join(ch for ch in (en or "").lower() if ch.isalnum())
    if slug in NEVER_PICTURE:
        return ""
    brand = BRAND_ART.get(slug, "")
    if brand:
        return brand
    if slug in REJECT_PHOTO:
        return ""
    hit = _photo_file(slug)
    if hit:
        return hit
    alias = PHOTO_ALIAS.get(slug, "")
    if alias in REJECT_PHOTO:
        return ""
    return _photo_file(alias)
