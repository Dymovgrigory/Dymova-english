_COLOUR = frozenset({"red", "blue", "green", "yellow", "black", "white", "brown", "orange", "pink", "grey", "gray"})
_ANIMAL = frozenset({"cat", "dog", "bird", "fish", "pet", "fox", "pig", "duck", "hen", "rat", "cow", "owl", "bee"})
_FAMILY = frozenset({"mum", "dad", "sister", "brother", "baby"})
_FEEL = frozenset({"happy", "sad", "hungry", "thirsty"})
_SIZE = frozenset({"big", "small"})
_NUM = frozenset({"one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"})


def _art(word: str) -> str:
    return "an" if (word[:1] in "aeiou") else "a"


def phrase_for(en: str, ru: str = "") -> tuple[str, str]:
    key = (en or "").lower()
    hit = PHRASE.get(key)
    if hit:
        return hit[0], ""
    if key in _COLOUR:
        return f"It is {key}.", ""
    if key in _FEEL:
        return f"I am {key}.", ""
    if key in _SIZE:
        return f"It is {key}.", ""
    if key in _NUM:
        return f"I see {key}.", ""
    if key == "family":
        return "This is my family.", ""
    if key in _FAMILY:
        return f"This is my {key}.", ""
    if key in _ANIMAL:
        return f"This is {_art(key)} {key}.", ""
    if key.isalpha() and len(key) > 2:
        return f"This is {_art(key)} {key}.", ""
    return en, ""


