def _sentences(text: str) -> list[str]:
    return [p.strip() for p in re.split(r"(?<=[.!?])\s+", text or "") if p.strip()]


def _four(src: list[dict], *, checkpoint: bool = False) -> list[dict]:
    if checkpoint:
        return [
            _c("1 · Цель урока", "Повторим модуль как контрольная: сначала правило, потом слух, потом короткие задания как в учебнике.", "foxi-hello", speak=""),
            _c("2 · Произношение", "Вспомни звук модуля. Слушай карточку. Повтори вслух три раза.", "consonants", speak=""),
            _c("3 · Фраза и диалог", "Скажи одну фразу модуля целиком, не по словам.", "foxi-hello", speak=""),
            _c("4 · Что ловит учитель", "Не угадывай. Не читай русскими буквами. Если забыл — вернись к образцу.", "wrap", speak=""),
        ]
    first = src[0] if src else WARMUP
    second = src[1] if len(src) > 1 else None
    body1 = (first.get("body_ru") or "").strip()
    body2 = (second.get("body_ru") or "").strip() if second else ""
    vis = first.get("visual_id") or "vowels"
    vis2 = (second or {}).get("visual_id") or "consonants"
    ex_en = first.get("example_en") or (second or {}).get("example_en", "")
    ex_ru = first.get("example_ru") or (second or {}).get("example_ru", "")
    title1 = first.get("title_ru") or "Цель урока"
    title2 = (second or {}).get("title_ru") or "Звук и буквы"
    how = body2 or (
        "Найди в тексте выше гласную и согласные. Сначала звук, потом слово-якорь. "
        "Повтори образец вслух."
    )
    trap_bits = _sentences(body1)[-2:] + _sentences(body2)[-2:]
    trap = " ".join(trap_bits).replace("Spotlight 2", "чтении").replace("Spotlight", "школе")
    if len(trap) < 40:
        trap = (
            f"На этом уроке легко спутать правило «{title1}». "
            "Не читай английское слово русскими буквами. Сначала слух, потом рот, потом задание."
        )
    return [
        _c(f"1 · {title1}", body1, vis, ex_en, ex_ru, speak=""),
        _c(f"2 · {title2}", how, vis2, ex_en, "", speak=ex_en),
        _c(
            "3 · Образец из урока",
            f"Фраза урока: {ex_en}. {ex_ru} "
            f"Говори её целиком. Потом разберём, где обычно ошибаются на теме «{title1}».",
            vis,
            ex_en,
            ex_ru,
            speak=ex_en,
        ),
        _c(f"4 · Ошибка темы «{title1}»", trap, "wrap", "", "", speak=""),
    ]


def head(unit_id: str, lesson_n: int, checkpoint: bool) -> list[dict]:
    pack = THEORY.get(unit_id) or []
    idx = lesson_n - 1
    src = pack[idx] if 0 <= idx < len(pack) else []
    return _four(src, checkpoint=checkpoint)


def wrap() -> dict:
    return WRAP
