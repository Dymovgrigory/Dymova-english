def _lesson(title: str, gpc: str, sound: str, how: str, trap: str,
            words: list[tuple], phrases: list[tuple]) -> dict:
    wds = [_w(*row) if len(row) == 3 else row for row in words]
    cards = _cards(gpc, sound, how, trap, wds)
    return {
        "title_ru": title,
        "gpc": gpc,
        "sound": sound,
        "cards": cards,
        "words": wds,
        "phrases": phrases,
    }


def _unit(uid: str, title: str, topic: str, goal: str, accent: str, lessons: list[dict]) -> dict:
    spots = [ls["title_ru"] for ls in lessons]
    words, phrases, seen = [], [], set()
    for ls in lessons:
        for w in ls["words"]:
            if w["en"] not in seen:
                seen.add(w["en"])
                words.append((w["en"], w["ipa"], w["ru"], w["en"], w["ru"]))
        phrases.extend(ls["phrases"])
    return {
        "id": uid,
        "book": BOOK,
        "book_ru": BOOK_RU,
        "place_ru": title,
        "topic_ru": topic,
        "goal_ru": goal,
        "accent": accent,
        "spots": spots,
        "has_checkpoint": True,
        "checkpoint_ru": f"Проверка: {topic}",
        "grammar": lessons[-1]["cards"][1:3],
        "theory": [ls["cards"][1] for ls in lessons],
        "words": words,
        "phrases": phrases,
        "lessons": lessons,
    }


