"""Склонение русских имён.

Нужно из-за редакции персональных данных (`app.pii`). Модель работает с
плейсхолдером вместо имени, и если разворачивать его всегда в именительном
падеже, получается «записываю Маша на диагностику» — ровно та робо-речь,
которой в живом диалоге быть не должно.

Поэтому модель может пометить падеж прямо в плейсхолдере
(`{{CHILD_NAME:вин}}`), а разворачиваем мы уже склонённую форму.

Это не морфологический анализатор: правил ровно столько, сколько нужно для
личных имён. Незнакомое окончание возвращается без изменений — исказить имя
хуже, чем оставить его в исходной форме.
"""
from __future__ import annotations

NOMINATIVE = "им"
CASES = (NOMINATIVE, "род", "дат", "вин", "твор", "пред")

# Шипящие определяют выбор окончания: «Маши», а не «Машы»; «Машей», а не «Машой».
_HUSHING = "гкхжчшщ"      # после них в родительном пишется «и»
_SOFT_INSTRUMENTAL = "жчшщц"  # после них в творительном «ей»/«ем»
_CONSONANTS = "бвгдзжклмнпрстфхцчшщ"


def decline(name: str, case: str) -> str:
    """Возвращает имя в указанном падеже.

    Составные значения («Иванова Анна») не склоняются: у фамилии и имени
    разные правила, и ошибка здесь заметнее, чем именительный падеж.
    """
    name = (name or "").strip()
    if not name or case == NOMINATIVE or case not in CASES:
        return name
    if " " in name:
        return name

    low = name.lower()
    last = low[-1]
    stem = name[:-1]
    prev = low[-2] if len(low) > 1 else ""

    if last == "я":
        if low.endswith("ия"):
            # Мария → Марии/Марии/Марию/Марией/Марии
            forms = {"род": "и", "дат": "и", "вин": "ю", "твор": "ей", "пред": "и"}
        else:
            # Настя, Женя → Насти/Насте/Настю/Настей/Насте
            forms = {"род": "и", "дат": "е", "вин": "ю", "твор": "ей", "пред": "е"}
        return stem + forms[case]

    if last == "а":
        # Одно правило и для женских (Анна), и для мужских (Миша, Никита) имён
        # на «-а»: склоняются они одинаково.
        genitive = "и" if prev in _HUSHING else "ы"
        instrumental = "ей" if prev in _SOFT_INSTRUMENTAL else "ой"
        forms = {"род": genitive, "дат": "е", "вин": "у", "твор": instrumental, "пред": "е"}
        return stem + forms[case]

    if last in "йь":
        # Андрей, Игорь → Андрея/Андрею/Андрея/Андреем/Андрее
        forms = {"род": "я", "дат": "ю", "вин": "я", "твор": "ем", "пред": "е"}
        return stem + forms[case]

    if last in _CONSONANTS:
        # Иван, Максим → Ивана/Ивану/Ивана/Иваном/Иване
        instrumental = "ем" if last in _SOFT_INSTRUMENTAL else "ом"
        forms = {"род": "а", "дат": "у", "вин": "а", "твор": instrumental, "пред": "е"}
        return name + forms[case]

    # Несклоняемые: Отто, Мери, Анеле и любые латинские написания.
    return name


__all__ = ["CASES", "NOMINATIVE", "decline"]
