"""Какой падеж требует место в предложении.

Модель работает с плейсхолдером вместо имени и может пометить падеж сама
(`{{CHILD_NAME:дат}}`), но регулярно этого не делает — и тогда имя
разворачивается в именительном: «поможет Аделина лучше понять», «уровень
английского у Аделина». Живой человек так не пишет, и это первое, что
выдаёт робота.

Здесь падеж определяется по словам перед именем: предлог задаёт падеж
жёстко, некоторые глаголы — почти жёстко. Правил ровно столько, сколько
встречается в разговоре о ребёнке и занятиях; в непонятном случае остаётся
именительный — исказить имя хуже, чем оставить исходную форму.
"""
from __future__ import annotations

import re

from app.morph import CASES, NOMINATIVE, decline

# Предлог однозначно задаёт падеж следующего за ним имени.
_PREPOSITION_CASE = {
    word: case
    for case, words in {
        "род": ("у", "для", "от", "до", "без", "около", "кроме", "после", "против", "насчёт"),
        "дат": ("к", "ко", "по", "благодаря"),
        "вин": ("про", "через", "сквозь"),
        "твор": ("с", "со", "перед", "над", "под", "между", "за"),
        "пред": ("о", "об", "обо", "при"),
    }.items()
    for word in words
}

# Служебные слова между управляющим словом и именем.
# «это» ведёт себя двояко: в «подойдёт ли это Аделине» оно служебное, а в
# «это Аделина» — указательное. Пропускаем его как служебное: если за ним
# ничего управляющего нет, падеж и так останется именительным.
_FILLER = ("ли", "бы", "же", "уже", "ещё", "еще", "вообще", "точно", "сейчас", "это")

# Слова, после которых имя стоит в дательном: «поможет Аделине»,
# «Аделине понравится», «сколько лет Аделине».
_DATIVE_VERBS = (
    "помож", "помога", "помочь", "подойд", "подход", "нравит", "понравит",
    "интересн", "удобн", "лет", "года", "сложно", "легко", "проще", "нужно",
)

# Слова, после которых имя стоит в винительном: «записать Аделину»,
# «ждём Аделину», «видели Аделину».
_ACCUSATIVE_VERBS = (
    "запиш", "записа", "записыва", "пригласи", "приглаша", "ждём", "ждем",
    "ждать", "видел", "встрет", "берём", "берем", "взять", "зовут",
)

# Сравнение «таким детям, как Аделина» — имя остаётся в именительном.
# После этих слов имя остаётся в именительном: «таким детям, как
# Аделина», «это Аделина».
_KEEP_NOMINATIVE = ("как", "зовут", "вот")

_WORD_RE = re.compile(r"[а-яёa-z]+", re.IGNORECASE)


def case_for(prefix: str) -> str:
    """Падеж имени, стоящего сразу после `prefix`.

    Решает ближайшее значимое слово: предлог задаёт падеж жёстко, глагол —
    почти жёстко. Служебные слова между ними («подойдёт ли это Аделине»)
    пропускаем, иначе управляющее слово теряется. Дальше трёх слов не
    заглядываем: там связь уже слишком слабая, чтобы менять имя.
    """
    words = _WORD_RE.findall((prefix or "").lower())
    if not words:
        return NOMINATIVE

    if words[-1] in _PREPOSITION_CASE:
        return _PREPOSITION_CASE[words[-1]]

    for word in reversed(words[-3:]):
        if word in _FILLER:
            continue
        if word in _KEEP_NOMINATIVE:
            return NOMINATIVE
        if word.startswith(_DATIVE_VERBS):
            return "дат"
        if word.startswith(_ACCUSATIVE_VERBS):
            return "вин"
        break
    return NOMINATIVE


def fix_names(text: str, names: list[str]) -> str:
    """Ставит имена в нужный падеж там, где они остались в именительном.

    Подстраховка для случая, когда имя попало в ответ мимо плейсхолдера —
    например, модель написала его словами. Трогаем только точное совпадение
    с именительной формой и только там, где предлог или глагол требуют
    другого падежа: уже склонённое имя не трогается, потому что не совпадает
    с исходной формой.
    """
    if not text or not names:
        return text
    for name in names:
        name = (name or "").strip()
        if len(name) < 3 or " " in name:
            continue
        pattern = re.compile(rf"(?<![А-Яа-яЁё]){re.escape(name)}(?![А-Яа-яЁё])")

        def replace(match: re.Match[str], _name: str = name) -> str:
            case = case_for(match.string[: match.start()])
            return decline(_name, case) if case != NOMINATIVE else _name

        text = pattern.sub(replace, text)
    return text


def is_case(value: str) -> bool:
    return value in CASES


__all__ = ["case_for", "fix_names", "is_case"]
