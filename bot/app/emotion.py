"""Эмоциональный слой: что человек чувствует прямо сейчас.

Раньше настроение было тумблером на два положения — «нужна эмпатия» и
«тепло», — и единственным его следствием была приставка «Понимаю, это
важно» перед любым ответом, включая рекламный. Между «мне тревожно за
ребёнка» и «мне надоело, что вы не перезваниваете» разницы не было никакой,
хотя отвечать на них надо противоположным образом.

Здесь состояния разделены по тому, что они меняют в ответе:

* `ANGRY` — человек недоволен школой. Предлагать ему что-либо нельзя,
  сначала разбираемся с тем, что случилось.
* `DISCOURAGED` — опустились руки («ничего не помогает», «уже пробовали»).
  Продавать тоже рано: сначала признать, что попытки были.
* `ANXIOUS` — тревога и сомнение. Продавать можно, но осторожно и без
  давления.
* `CONFUSED` — человек не понял сказанного. Предлагать что-то поверх
  непонимания бессмысленно: сначала объяснить проще.
* `WARM` / `CURIOUS` / `NEUTRAL` — обычный разговор.

Слой детерминированный. Модель здесь не нужна: эмоция управляет запретами,
а запрет, который зависит от доступности провайдера, — это не запрет.
"""
from __future__ import annotations

import re

NEUTRAL = "neutral"
CURIOUS = "curious"
WARM = "warm"
ANXIOUS = "anxious"
DISCOURAGED = "discouraged"
CONFUSED = "confused"
ANGRY = "angry"

# Состояния, при которых предлагать курс, диагностику и запись нельзя.
# ТЗ формулирует это прямо: «Если человек раздражён — не рекламируй».
_NO_OFFER = frozenset({ANGRY, DISCOURAGED, CONFUSED})

_ANGRY_RE = re.compile(
    r"жалоб|недоволь|претенз|возмут|безобрази|хамств|"
    r"никто не (?:перезвонил|ответил|отвечает)|не перезвонил|не отвеча[ею]т|"
    r"игнорир|сколько можно|достал|надоел|раздража|бесит|злит|"
    r"верните деньги|вернуть деньги|"
    r"обман|развод|отврат|ужасн|хуже некуда",
    re.IGNORECASE,
)

_DISCOURAGED_RE = re.compile(
    r"ничего не помога|уже (?:всё |все )?пробовал|ничего не выход|"
    r"опускаются руки|опустились руки|бесполезно|не вижу смысла|"
    r"устал[аи]? (?:уже )?(?:от|бороться|воевать)|сдал[аи]сь|"
    r"ненавидит английск|терпеть не может английск",
    re.IGNORECASE,
)

_CONFUSED_RE = re.compile(
    r"не понима|не понял|не поняла|непонятн|запутал|"
    r"что вы имеете в виду|о ч[ёе]м вы|можно проще",
    re.IGNORECASE,
)

_ANXIOUS_RE = re.compile(
    r"переживаю|волну|тревож|боюсь|страшно|"
    r"не уверен|сомнева|вдруг не|а если не|"
    r"отстаёт|отстает|не тянет|не справля|"
    r"успеем ли|получится ли",
    re.IGNORECASE,
)

_WARM_RE = re.compile(
    r"спасибо|благодар|отличн|супер|здорово|класс|"
    r"то, что нужно|очень помог|рад[аы]? слышать",
    re.IGNORECASE,
)

# Раздражение редко приходит одним словом — чаще это заглавные буквы и
# несколько восклицательных знаков подряд.
_SHOUTING_RE = re.compile(r"[!]{2,}")

# Подтверждения ТЗ: реплики-признания эмоции, а не заготовки «Понимаю вас».
# Пустая строка означает «начинай сразу с сути» — фраза-затычка перед каждым
# ответом раздражает сильнее, чем её отсутствие.
_OPENERS = {
    ANGRY: "Извините за эту ситуацию. ",
    DISCOURAGED: "Понимаю, это выматывает. ",
    ANXIOUS: "Понимаю ваше беспокойство. ",
    CONFUSED: "Объясню понятнее. ",
    WARM: "",
    CURIOUS: "",
    NEUTRAL: "",
}


def detect(text: str, previous: str = "") -> str:
    """Состояние собеседника по последней реплике.

    `previous` — состояние с прошлой реплики: недовольство не проходит от
    того, что человек написал следующее сообщение спокойнее, и переключаться
    с него на бодрый тон нельзя, пока причина не снята.
    """
    if not text or not text.strip():
        return previous or NEUTRAL

    if _ANGRY_RE.search(text) or _is_shouting(text):
        return ANGRY
    if _DISCOURAGED_RE.search(text):
        return DISCOURAGED
    if _CONFUSED_RE.search(text):
        return CONFUSED
    if _ANXIOUS_RE.search(text):
        return ANXIOUS
    if _WARM_RE.search(text):
        # Благодарность после недовольства — это разрядка, а не праздник:
        # тон возвращаем к нейтральному, а не к бодрому.
        return NEUTRAL if previous == ANGRY else WARM
    if previous in (ANGRY, DISCOURAGED):
        # Молча «забыть» недовольство нельзя: пока не прояснили, что
        # случилось, разговор всё ещё идёт на этом фоне.
        return previous
    if "?" in text:
        return CURIOUS
    return NEUTRAL


def _is_shouting(text: str) -> bool:
    if _SHOUTING_RE.search(text):
        return True
    letters = [ch for ch in text if ch.isalpha()]
    if len(letters) < 12:
        # Короткое «ОК» капсом — не крик.
        return False
    upper = sum(1 for ch in letters if ch.isupper())
    return upper / len(letters) > 0.7


def allows_offer(state: str) -> bool:
    """Можно ли в этом состоянии вообще что-то предлагать."""
    return state not in _NO_OFFER


def opening(state: str) -> str:
    """Признание эмоции перед ответом. Пустая строка — говорить по сути."""
    return _OPENERS.get(state, "")


def prompt_block(state: str) -> str:
    """Инструкция модели о том, как держать тон в этом состоянии."""
    if state == ANGRY:
        return (
            "\nСОСТОЯНИЕ СОБЕСЕДНИКА: он недоволен. Сначала признай проблему и "
            "разберись, что произошло. Ничего не предлагай, не рекламируй "
            "школу и не зови записываться — это воспринимается как "
            "издевательство. Никакой бодрости и восклицаний."
        )
    if state == DISCOURAGED:
        return (
            "\nСОСТОЯНИЕ СОБЕСЕДНИКА: у него опустились руки. Признай, что "
            "попытки уже были, и покажи, что понимаешь причину. Не предлагай "
            "курс и не обещай быстрый результат."
        )
    if state == CONFUSED:
        return (
            "\nСОСТОЯНИЕ СОБЕСЕДНИКА: он не понял предыдущий ответ. Объясни то "
            "же самое проще и другими словами, без терминов и без новых тем. "
            "Ничего не предлагай, пока не станет понятно."
        )
    if state == ANXIOUS:
        return (
            "\nСОСТОЯНИЕ СОБЕСЕДНИКА: он переживает. Отвечай спокойно и "
            "конкретно, без давления и без срочности."
        )
    return ""


