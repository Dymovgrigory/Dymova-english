_CANONICAL: dict[str, set[str]] = {}
for full, forms in _FORMS.items():
    for form in (full, *forms):
        _CANONICAL.setdefault(form, set()).add(full)


def canonical_names(name: str) -> set[str]:
    """Полные имена, которые может означать эта форма. Незнакомое имя — само себя."""
    return _CANONICAL.get(name, {name})


def all_forms(name: str) -> set[str]:
    """Все написания того же имени: «миша» → {«михаил», «миша»}."""
    out: set[str] = set()
    for full in canonical_names(name):
        out.add(full)
        out.update(_FORMS.get(full, ()))
    return out
