"""Помощник по школьной домашке: единый тьютор для всех каналов.

Раньше педагогика жила в main.py и работала только в вебхуках MAX/Telegram,
а мини-приложение и веб-виджет отвечали общей консультацией с markdown-
мусором. Теперь модуль общий: один промпт, одна зачистка, один разбор —
везде одинаковая подача.
"""
