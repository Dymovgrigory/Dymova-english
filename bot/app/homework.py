# Модель держит формат заметно лучше, когда видит образец, а не только
# словесное описание (проверено на проде gpt-4o-mini, сессия 78). Образец
# показывает ДВА блока «🔎 Пункт N», чтобы паттерн «один блок на каждый
# пункт задания» был однозначно понятен модели, а не угадывался из прозы.
_FORMAT_TEMPLATE = (
    "\n\nОформи ответ СТРОГО по этому образцу (с эмодзи, с пустыми строками "
    "между частями):\n\n"
    "📘 Правило\n"
    "<тема и правило простыми словами, 2–3 предложения>\n\n"
    "🔎 Пункт 1\n"
    "<какое правило применить именно в этом пункте задания, КУДА смотреть "
    "(например, «посмотри на подлежащее»), с чего начать — без готового "
    "ответа и без " + _DECIDING_FEATURE_HINT + ">\n\n"
    "🔎 Пункт 2\n"
    "<то же самое для второго пункта задания; блок «🔎 Пункт N» повторяется "
    "по одному на каждый пункт — если пункт в задании всего один, оставь "
    "только «🔎 Пункт 1»>\n\n"
    "✏️ Похожий пример\n"
    "<ОДНО придуманное похожее задание и его решение по шагам 1) 2) 3); "
    "по английскому — пример на английском>\n\n"
    "✅ План для твоего задания\n"
    "1) <шаг>\n2) <шаг>\n3) <шаг>\n\n"
    "❓ <вопрос: предложи попробовать и написать, что получилось>\n\n"
    "Образец блока «✏️ Похожий пример» для задания по английскому "
    "(задание: напиши о погоде в 4 городах — Москва, Рим, Париж, Каир):\n"
    "✏️ Похожий пример\n"
    "Возьмём город, которого нет в задании, — Лондон.\n"
    "1) It will be rainy in London tomorrow.\n"
    "2) Мы использовали конструкцию It will be + погода, потому что говорим "
    "о прогнозе на завтра.\n"
    "Обрати внимание: пример один (один город), и его нет среди пунктов "
    "задания."
)


_MD_BOLD = re.compile(r"\*\*(.+?)\*\*")
_MD_HEADING = re.compile(r"^#{1,6}\s*", re.MULTILINE)
_MD_BULLET = re.compile(r"^(\s*)[*+]\s+", re.MULTILINE)
_MD_TABLE_EDGE = re.compile(r"^\s*\||\|\s*$", re.MULTILINE)


def _strip_markdown(text: str) -> str:
    """Чистим ответ модели от markdown-разметки.

    MAX/Telegram-чаты школы не рендерят markdown: «**правило**» приходит
    ребёнку со звёздочками и читается как мусор. Промпт запрещает разметку,
    но модели периодически её вставляют — зачищаем на выходе.

    Одиночные * и _ сознательно НЕ трогаем: в школьных заданиях это
    умножение («3 * 4») и пропуски («I __ nine») — они важнее разметки.
    """
    cleaned = _MD_HEADING.sub("", text)
    cleaned = _MD_BOLD.sub(r"\1", cleaned)
    cleaned = _MD_BULLET.sub(r"\1— ", cleaned)
    cleaned = cleaned.replace("`", "")
    # Таблицы в чате нечитаемы совсем: убираем разделители, оставляем текст.
    cleaned = _MD_TABLE_EDGE.sub("", cleaned)
    cleaned = re.sub(r"^\s*\|[\s:|-]+\|?\s*$", "", cleaned, flags=re.MULTILINE)
    # Пустых строк подряд больше двух не нужно.
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned.strip()


# Маркеры разделов тьютора. Модель часто пишет «📘 Правило Текст…» в одну
# строку без пустых строк между разделами — расставляем их детерминированно.
# 🔎 — разбор отдельного пункта задания (их может быть несколько подряд).
_TUTOR_SECTION_RE = re.compile(r"\s*(📘|🔎|✏️|✏|✅|❓)\s*")


def _format_tutor_reply(text: str) -> str:
    """Перенос строки перед каждым маркером раздела и после заголовка-маркера.

    «📘 Правило В английском… 🔎 Пункт 1 Смотри… 🔎 Пункт 2 Смотри…
    ✏️ Похожий пример Давай…» →
    «📘 Правило\nВ английском…\n\n🔎 Пункт 1\nСмотри…\n\n🔎 Пункт 2\nСмотри…\n\n
    ✏️ Похожий пример\nДавай…».
    """
    out = _TUTOR_SECTION_RE.sub(r"\n\n\1 ", text)
    # Убираем склейку заголовка с телом: «📘 Правило В английском» → перенос
    # после известных слов-заголовков. «🔎 Пункт N» — с переменным номером,
    # поэтому это регэксп с \d+, а не буквальная строка, как у остальных.
    out = re.sub(
        r"(📘 Правило|🔎 Пункт \d+|✏️ Похожий пример|✏ Похожий пример|"
        r"✅ План для твоего задания)\s+",
        r"\1\n",
        out,
    )
    out = re.sub(r"\n{3,}", "\n\n", out)
    return out.strip()


def _finalize_tutor_reply(reply: str | None) -> str | None:
    if not reply:
        return None
    return _format_tutor_reply(_strip_markdown(reply))


