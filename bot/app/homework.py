# Единая формулировка «любой признак, который выдаёт ответ через
# исключение» — используется дословно в системном промпте режима проверки,
# в пользовательском промпте режима проверки и в критике (kind="check"), а
# теперь и в режиме разбора (system-промпт, шаблон разбора по пунктам и
# критик kind="explain") — см. финальное ревью Task 8: у разбора не было
# такой защиты вовсе, хотя это самый частый режим всей фичи. Ревью нашло
# дыру в прежней версии: список «число, лицо, время, часть речи» — только
# грамматические признаки, а для a/an решающий признак ФОНЕТИЧЕСКИЙ
# (гласный/согласный звук следующего слова) — он не попадал под
# перечисление, хотя a/an сам был назван в примерах поддерживаемых заданий.
# Формулировка ниже — общая («любой признак..., который...»), а
# грамматический/звуковой/орфографический — иллюстрации, не исчерпывающий
# список. Общий для всех промптов текст (не копия в каждом) устраняет и
# риск разъезда формулировок между местами при будущих правках. Константа
# объявлена здесь, до всех промптов, которые её используют, — в том числе
# до модульных строк-констант (_FORMAT_TEMPLATE), которые вычисляются один
# раз при импорте, а не внутри функции.
_DECIDING_FEATURE_HINT = (
    "любой признак, который в задании с выбором из двух вариантов "
    "однозначно определяет ответ через исключение второго варианта — не "
    "только грамматический (число, лицо, время, часть речи), но и "
    "звуковой (например, для a/an — с какого звука начинается следующее "
    "слово: гласного или согласного) или орфографический"
)


def save_homework_image(image_bytes: bytes, ext: str = "jpg") -> str:
    """Сохраняет фото задания на диск. Возвращает относительный путь вида
    "homework/<uuid>.<ext>" — так же, как ссылки на другие данные в /app/data."""
    directory = Path(HOMEWORK_IMAGE_DIR)
    directory.mkdir(parents=True, exist_ok=True)
    filename = f"{uuid.uuid4().hex}.{ext}"
    (directory / filename).write_bytes(image_bytes)
    return f"homework/{filename}"


