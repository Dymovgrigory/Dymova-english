"""Занятия на базе школ: гимназия 13 и школа 14.

Для этих площадок действует своя цена, а расписание бот не называет: оно
меняется вместе со школьным и известно только администратору. Раньше на
вопросы про гимназию 13 бот выдавал общий список групп филиалов и цену
9 000 ₽ — оба ответа были неверны (слова владельца, 2026-09-30).
"""
from __future__ import annotations

import re

PRICE_PER_MONTH = "8 000 ₽"

# «гимназия 13», «13 гимназии», «школа №14», «14-й школе». Число обязательно
# рядом со словом: «13 класс» и «14 лет» не срабатывают.
_NUM = r"(?:№|n|#)?\s*"
_ORD = r"(?:-?(?:й|ой|я|ю|е))?"
_SITE_RE = re.compile(
    rf"гимнази\w*\s*{_NUM}13\b|13{_ORD}\s*гимнази\w*"
    rf"|школ\w*\s*{_NUM}14\b|14{_ORD}\s*школ\w*",
    re.IGNORECASE,
)

REPLY = (
    "Да, занятия на базе гимназии №13 и школы №14 у нас есть — "
    f"{PRICE_PER_MONTH} в месяц 😊\n\n"
    "Расписание для этих площадок уточняет администратор: передаю ему ваш "
    "вопрос, он свяжется с вами и подберёт удобные дни и время. "
    "Если удобнее позвонить — 8 993 923-23-09 или 8 916 732-31-69."
)


def mentions_school_site(text: str) -> bool:
    return bool(_SITE_RE.search(text or ""))
